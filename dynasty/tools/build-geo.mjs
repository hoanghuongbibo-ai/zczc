// Builds dynasty/js/geo-colonies.js (lon/lat outlines for the Revolution maps) from Natural Earth via npm.
// usage: node dynasty/tools/build-geo.mjs <dir with node_modules containing us-atlas@3, world-atlas@2, topojson-client@3>
// Output: G.Geo = { land: [rings], states: { NY: [rings], ... } } — rings are [[lon, lat], ...], simplified.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const dir = path.resolve(process.argv[2] || '.');
const req = createRequire(path.join(dir, 'x.js'));
const topo = req('topojson-client');
const load = p => JSON.parse(fs.readFileSync(req.resolve(p), 'utf8'));
const BOX = [-92, 24, -56, 52];                     // lon0, lat0, lon1, lat1 (Georgia → Nova Scotia, Ohio → Atlantic)
const TOL = .012;                                   // Douglas–Peucker tolerance in degrees (~1 km)

function dp(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let best = -1, bi = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / L; if (d > best) { best = d; bi = i; } }
    if (best > tol) { keep[bi] = 1; st.push([a, bi], [bi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const inBox = r => r.some(([x, y]) => x >= BOX[0] && x <= BOX[2] && y >= BOX[1] && y <= BOX[3]);
const area = r => Math.abs(r.reduce((s, [x, y], i) => { const [x2, y2] = r[(i + 1) % r.length]; return s + x * y2 - x2 * y; }, 0) / 2);
// Sutherland–Hodgman clip of a ring to the box (keeps the continent ring small).
function clip(r) {
  const edges = [[p => p[0] >= BOX[0], (a, b) => cut(a, b, 0, BOX[0])], [p => p[0] <= BOX[2], (a, b) => cut(a, b, 0, BOX[2])],
    [p => p[1] >= BOX[1], (a, b) => cut(a, b, 1, BOX[1])], [p => p[1] <= BOX[3], (a, b) => cut(a, b, 1, BOX[3])]];
  function cut(a, b, ax, v) { const k = (v - a[ax]) / (b[ax] - a[ax]); return [a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k]; }
  for (const [inside, isect] of edges) {
    const res = [];
    for (let i = 0; i < r.length; i++) { const a = r[i], b = r[(i + 1) % r.length];
      if (inside(b)) { if (!inside(a)) res.push(isect(a, b)); res.push(b); } else if (inside(a)) res.push(isect(a, b)); }
    r = res; if (!r.length) break;
  }
  return r;
}
const rnd = r => r.map(([x, y]) => [+x.toFixed(3), +y.toFixed(3)]);
function rings(geom, minArea = .002) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.type === 'MultiPolygon' ? geom.coordinates : [];
  return polys.map(p => p[0]).filter(r => inBox(r) && area(r) > minArea).map(r => rnd(dp(clip(r.slice(0, -1)), TOL))).filter(r => r.length > 2);   // drop the closing point (DP needs distinct ends)
}

const world = load('world-atlas/land-10m.json');
const land = topo.feature(world, world.objects.land).features.flatMap(f => rings(f.geometry));

const us = load('us-atlas/states-10m.json');
const WANT = { 'New Hampshire': 'NH', Massachusetts: 'MA', Maine: 'ME', 'Rhode Island': 'RI', Connecticut: 'CT', 'New York': 'NY',
  'New Jersey': 'NJ', Pennsylvania: 'PA', Delaware: 'DE', Maryland: 'MD', Virginia: 'VA', 'North Carolina': 'NC',
  'South Carolina': 'SC', Georgia: 'GA', Vermont: 'VT', 'West Virginia': 'WV', Kentucky: 'KY', Tennessee: 'TN', Ohio: 'OH',
  'District of Columbia': 'DC' };
const states = {};
for (const f of topo.feature(us, us.objects.states).features) { const k = WANT[f.properties.name]; if (k) states[k] = rings(f.geometry, .0005); }

const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../js/geo-colonies.js');
fs.writeFileSync(out, '/* Generated by dynasty/tools/build-geo.mjs from Natural Earth (world-atlas land-10m) + US Census (us-atlas states-10m). Do not edit. */\n' +
  `window.Geo = ${JSON.stringify({ box: BOX, land, states })};\n`);
console.log('wrote', out, (fs.statSync(out).size / 1024).toFixed(0) + ' KB', 'land rings', land.length, 'states', Object.keys(states).length);
