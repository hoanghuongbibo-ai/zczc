#!/usr/bin/env python3
"""Anchor lookup for the Vindolanda voice: finds a (recognised) word sequence near an approximate time in the
pocketsphinx transcript and writes js/timing.js (window.TV = { key: seconds }). usage: tools_anchor.py asr.json"""
import json, sys
W = [w for s in json.load(open(sys.argv[1])) for w in s['words']]
def at(approx, phrase):
    ws = phrase.split(); best = None
    for i in range(len(W) - len(ws) + 1):
        if all(W[i + k][0] == ws[k] for k in range(len(ws))):
            d = abs(W[i][1] - approx)
            if best is None or d < best[0]: best = (d, W[i][1])
    if best is None or best[0] > 6: raise SystemExit(f'not found near {approx}: {phrase}')
    return round(best[1], 2)
A = {}
for line in open(sys.argv[2]):
    line = line.strip()
    if not line or line.startswith('#'): continue
    key, t, phrase = line.split('|'); A[key.strip()] = at(float(t), phrase.strip())
open(sys.argv[3], 'w').write('/* generated by tools_anchor.py from the voice transcript */\nwindow.TV = ' + json.dumps(A, indent=0) + ';\n')
print(len(A), 'anchors')
