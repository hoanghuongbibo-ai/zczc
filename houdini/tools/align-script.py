#!/usr/bin/env python3
"""Align a spoken-script text file to the narration's ASR word timings (any episode).

usage: python3 tools/align-script.py <narration.txt> <asr.json> <out-dir>
  narration.txt  the script exactly as recorded, one paragraph per line (numbers spelled out)
  asr.json       tools/asr.py output: [{a, b, words: [[word, start, end], ...]}, ...]
Splits the text into SENTENCES (= transcript lines, numbered from 1) and writes
  <out-dir>/js/timing.js     window.TV = {L<n>: first-word time}, window.TW = {n: [time of every word]}
  <out-dir>/transcript.txt   "  12.34  sentence text" per line (the reference for C(n, k) anchors)
Words are matched with difflib; unmatched script words are interpolated between their matched neighbours.
"""
import difflib, json, os, re, sys

txt, asr, out = sys.argv[1:4]
paras = [p.strip() for p in open(txt, encoding='utf-8') if p.strip()]
sents = []
for p in paras:
    for s in re.split(r'(?<=[.?!])\s+(?=[A-Z0-9"\'])', p):
        if s.strip(): sents.append(s.strip())
norm = lambda w: re.sub(r"[^a-z0-9']", '', w.lower().replace('’', "'"))
words, owner = [], []
for i, s in enumerate(sents):
    for w in s.split():
        n = norm(w)
        if n: words.append(n); owner.append(i)
A = [(norm(w[0]), w[1]) for seg in json.load(open(asr)) for w in seg['words'] if norm(w[0])]
sm = difflib.SequenceMatcher(None, words, [a[0] for a in A], autojunk=False)
T = [None] * len(words)
for blk in sm.get_matching_blocks():
    for k in range(blk.size): T[blk.a + k] = A[blk.b + k][1]
# fill gaps: replace/insert opcodes give us equal-length spans we can map position-wise
for tag, i1, i2, j1, j2 in sm.get_opcodes():
    if tag == 'replace':
        for k in range(i2 - i1):
            jj = j1 + int(k * (j2 - j1) / max(1, i2 - i1))
            if jj < j2: T[i1 + k] = A[jj][1]
matched = sum(t is not None for t in T)
# interpolate the rest
known = [i for i, t in enumerate(T) if t is not None]
for i in range(len(T)):
    if T[i] is None:
        lo = max([k for k in known if k < i], default=None); hi = min([k for k in known if k > i], default=None)
        if lo is None: T[i] = T[hi] - .3 * (hi - i)
        elif hi is None: T[i] = T[lo] + .3 * (i - lo)
        else: T[i] = T[lo] + (T[hi] - T[lo]) * (i - lo) / (hi - lo)
for i in range(1, len(T)): T[i] = max(T[i], T[i - 1] + .01)   # monotonic
TW = {}
for w, (i, t) in enumerate(zip(owner, T)): TW.setdefault(i + 1, []).append(round(t, 2))
os.makedirs(os.path.join(out, 'js'), exist_ok=True)
with open(os.path.join(out, 'js', 'timing.js'), 'w') as f:
    f.write('/* generated by tools/align-script.py: TV.L<n> = first-word time of sentence n (transcript.txt); TW[n][k] = k-th word. */\n')
    f.write('window.TV = ' + json.dumps({f'L{n}': v[0] for n, v in TW.items()}, indent=0) + ';\n')
    f.write('window.TW = ' + json.dumps({n: v for n, v in TW.items()}) + ';\n')
with open(os.path.join(out, 'transcript.txt'), 'w') as f:
    for n, s in enumerate(sents, 1): f.write(f'{TW[n][0]:7.2f}  {s}\n')
print(f'{len(sents)} sentences, {len(words)} words, {matched} matched ({matched / len(words):.0%})')
