#!/usr/bin/env python3
"""Mouth shapes (visemes) from the narration audio, one per video frame — for lip-sync.

usage: python3 tools/visemes.py narration.mp3 out.js [fps]
Writes `window.VIS = { fps, o: [...], k: "XAAEEO..." }`:
  o  mouth opening 0..1 (loudness, normalised to the 95th percentile)
  k  viseme per frame:  X rest · A open "ah" · E wide "ee/eh" · O round "oh/oo" · S teeth "s/f/sh/th" · M closed "m/b/p"
Rules (cheap but convincing for a cartoon): energy decides open/closed; the spectrum decides the shape —
low-heavy + dark → O, bright → E, hissy + quiet → S, short energy dips inside speech → M (lip closures).
"""
import subprocess, sys, json
import numpy as np

src, out = sys.argv[1], sys.argv[2]
fps = int(sys.argv[3]) if len(sys.argv) > 3 else 30
SR = 16000
raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', src, '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'], capture_output=True, check=True).stdout
x = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768
hop = SR / fps; n = int(len(x) / hop); win = 1024
freqs = np.fft.rfftfreq(win, 1 / SR); w = np.hanning(win)
band = lambda a, b: (freqs >= a) & (freqs < b)
LO, MID, HI = band(80, 500), band(500, 2200), band(2200, 7000)
rms = np.zeros(n); lo = np.zeros(n); mid = np.zeros(n); hi = np.zeros(n); cen = np.zeros(n)
for i in range(n):
    c = int(i * hop + hop / 2); s = x[max(0, c - win // 2): c + win // 2]
    if len(s) < win: s = np.pad(s, (0, win - len(s)))
    rms[i] = np.sqrt(np.mean(s ** 2) + 1e-12)
    P = np.abs(np.fft.rfft(s * w)) ** 2 + 1e-12; tot = P[LO | MID | HI].sum()
    lo[i], mid[i], hi[i] = P[LO].sum() / tot, P[MID].sum() / tot, P[HI].sum() / tot
    cen[i] = (P * freqs).sum() / P.sum()
o = np.clip(rms / (np.percentile(rms, 95) + 1e-9), 0, 1)
o = np.convolve(o, [.25, .5, .25], mode='same')
V = o >= .1                      # voiced/sounding frames; thresholds adapt to this voice
c_lo, c_hi = np.percentile(cen[V], 28), np.percentile(cen[V], 70); h_hi = np.percentile(hi[V], 88)
k = []
for i in range(n):
    if o[i] < .1: k.append('X'); continue
    if hi[i] >= h_hi and o[i] < .6: k.append('S')
    elif cen[i] <= c_lo: k.append('O')
    elif cen[i] >= c_hi: k.append('E')
    else: k.append('A')
# lip closures: a short dip (≥35% below both neighbours within 4 frames) inside speech → M
for i in range(2, n - 2):
    if k[i] == 'X': continue
    a, b = o[max(0, i - 4):i].max(), o[i + 1:i + 5].max()
    if o[i] < .5 * min(a, b) and o[i] < .38: k[i] = 'M'
# hold each shape at least 2 frames so the mouth doesn't flicker
for i in range(1, n - 1):
    if k[i] != k[i - 1] and k[i] != k[i + 1] and k[i] != 'M': k[i] = k[i - 1]
open(out, 'w').write('/* generated by tools/visemes.py — per-frame mouth opening + viseme for lip-sync */\nwindow.VIS = '
                     + json.dumps({'fps': fps, 'o': [round(float(v), 2) for v in o], 'k': ''.join(k)}, separators=(',', ':')) + ';\n')
from collections import Counter; print(n, 'frames', dict(Counter(k)))
